<?php

namespace Tests\Feature\Exports;

use App\Enums\ReportType;
use App\Models\Category;
use App\Models\Item;
use App\Models\ReportExport;
use App\Models\User;
use App\Reports\ReportFilters;
use App\Reports\ReportResult;
use App\Services\ReportService;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Testing\TestResponse;
use RuntimeException;
use Tests\TestCase;

/**
 * GET /reports/{type}/export: BACKEND_HANDOFF.md 4.8, "Export".
 *
 * ReportService::build() is Developer A's (phase 5) and is replaced here by a fake report with the
 * agreed ReportResult shape, so these tests check the export only: the file, the log, the errors.
 */
class ExportReportTest extends TestCase
{
    use RefreshDatabase;

    private User $sara;

    private Category $consumables;

    private Item $gloves;

    protected function setUp(): void
    {
        parent::setUp();
        $this->travelTo('2026-11-19 10:30');
        $this->sara = User::factory()->admin()->create(['name' => 'Sara Ahmed']);
        $this->consumables = Category::factory()->create(['name' => 'Consumables']);
        $this->gloves = Item::factory()->create(['name' => 'Surgical Gloves', 'category_id' => $this->consumables->id, 'unit' => 'box']);
    }

    // ---- The CSV file ----------------------------------------------------------------------

    public function test_a_summary_csv_has_the_report_information_the_table_and_the_totals(): void
    {
        $this->fakeReport(new ReportResult(ReportType::Summary,
            ['totalItems' => 1, 'available' => 0, 'lowStock' => 1, 'outOfStock' => 0], [],
            [['id' => 1, 'itemId' => $this->gloves->id, 'categoryId' => $this->consumables->id, 'quantity' => 8,
                'expiredQuantity' => 2, 'unit' => 'box', 'totalValue' => 96.456, 'status' => 'low_stock']]));

        $response = $this->actingAsAdmin($this->sara)->get('/api/reports/summary/export?format=csv')
            ->assertOk()
            ->assertHeader('Content-Type', 'text/csv; charset=UTF-8')
            ->assertHeader('Content-Disposition', 'attachment; filename="meditrack-summary-2026-11-19.csv"');

        $this->assertStringStartsWith("\xEF\xBB\xBF", $response->getContent(), 'UTF-8 mark for Excel');
        $this->assertSame([
            ['Report', 'Inventory Summary'],
            ['Generated by', 'Sara Ahmed (Admin)'],
            ['Generated at', '2026-11-19 10:30 (Asia/Gaza)'],
            ['Period', 'As of today'],
            ['Category', 'All categories'],
            ['Item', 'All items'],
            ['Rows', '1'],
            [],
            ['Item', 'Category', 'Available Quantity', 'Expired Quantity', 'Unit', 'Status', 'Total Value'],
            ['Surgical Gloves', 'Consumables', '8', '2', 'box', 'Low Stock', '96.46'],
            [],
            ['Totals'],
            ['Total Items', '1'], ['Available', '0'], ['Low Stock', '1'], ['Out of Stock', '0'],
        ], $this->csv($response));
    }

    public function test_movement_history_names_every_filter_and_each_type(): void
    {
        $this->fakeReport(new ReportResult(ReportType::MovementHistory,
            ['incomingCount' => 1, 'outgoingCount' => 1, 'disposalCount' => 1, 'itemsCount' => 1, 'transactionsCount' => 3], [],
            [
                ['id' => 3, 'itemId' => $this->gloves->id, 'type' => 'outgoing', 'reason' => 'expired_disposal', 'quantity' => 2,
                    'date' => '2026-11-15', 'supplier' => null, 'recipient' => null, 'unitCost' => 12, 'totalValue' => 24],
                ['id' => 2, 'itemId' => $this->gloves->id, 'type' => 'outgoing', 'reason' => 'issue', 'quantity' => 5,
                    'date' => '2026-11-10', 'supplier' => null, 'recipient' => 'Ward A', 'unitCost' => 12, 'totalValue' => 60],
                ['id' => 1, 'itemId' => $this->gloves->id, 'type' => 'incoming', 'reason' => null, 'quantity' => 15,
                    'date' => '2026-11-01', 'supplier' => 'MedSupply', 'recipient' => null, 'unitCost' => 12, 'totalValue' => null],
            ]));
        $query = "format=csv&from=2026-10-20&to=2026-11-19&categoryId={$this->consumables->id}&itemId={$this->gloves->id}&search=+glo+";

        $lines = $this->csv($this->actingAsStorekeeper()->get("/api/reports/movement_history/export?{$query}")->assertOk());

        $this->assertSame(['Period', '2026-10-20 to 2026-11-19'], $lines[3]);
        $this->assertSame([['Category', 'Consumables'], ['Item', 'Surgical Gloves'], ['Search', 'glo'], ['Rows', '3']], array_slice($lines, 4, 4));
        $this->assertSame(['Date', 'Item', 'Type', 'Quantity', 'Unit', 'Supplier', 'Recipient', 'Unit Cost', 'Total Value'], $lines[9]);
        $this->assertSame([
            ['2026-11-15', 'Surgical Gloves', 'Expired Disposal', '2', 'box', '', '', '12', '24'],
            ['2026-11-10', 'Surgical Gloves', 'Outgoing', '5', 'box', '', 'Ward A', '12', '60'],
            // A missing value stays empty instead of a made-up 0.
            ['2026-11-01', 'Surgical Gloves', 'Incoming', '15', 'box', 'MedSupply', '', '12', ''],
        ], array_slice($lines, 10, 3));
    }

    public function test_the_report_is_built_with_the_filters_and_every_row(): void
    {
        $this->mock(ReportService::class)->shouldReceive('build')->once()
            ->withArgs(fn (ReportType $type, ReportFilters $filters, ?int $page = null, ?int $pageSize = null) => $type === ReportType::InventoryValue
                && $filters->from->toDateString() === '2026-10-01' && $filters->categoryId === $this->consumables->id
                && $page === null && $pageSize === null)
            ->andReturn($this->emptyReport(ReportType::InventoryValue));

        $this->actingAsAdmin($this->sara)
            ->get("/api/reports/inventory_value/export?format=csv&from=2026-10-01&categoryId={$this->consumables->id}")
            ->assertOk();
    }

    public function test_a_name_that_looks_like_a_formula_stays_text(): void
    {
        $this->gloves->update(['name' => '=HYPERLINK("http://bad.example")']);
        $this->fakeReport(new ReportResult(ReportType::CriticalItems,
            ['totalItems' => 1, 'lowStock' => 1, 'outOfStock' => 0, 'expired' => 0, 'expiringSoon' => 1, 'expiring' => 1, 'alerts' => 2], [],
            [
                ['id' => 'low_stock-1', 'itemId' => $this->gloves->id, 'categoryId' => $this->consumables->id, 'quantity' => 8, 'minQty' => 15, 'unit' => 'box', 'status' => 'low_stock'],
                ['id' => 'expiring_soon-1', 'itemId' => $this->gloves->id, 'categoryId' => $this->consumables->id, 'quantity' => 8, 'minQty' => 15, 'unit' => 'box', 'status' => 'expiring_soon'],
            ]));

        $lines = $this->csv($this->actingAsAdmin($this->sara)->get('/api/reports/critical_items/export?format=csv')->assertOk());

        $this->assertSame(["'=HYPERLINK(\"http://bad.example\")", 'Consumables', 'Low Stock', '8', '15', 'box'], $lines[9]);
        $this->assertSame('', $lines[10][4], 'no minimum on an expiry row');
    }

    // ---- The export log --------------------------------------------------------------------

    public function test_a_successful_export_is_logged_with_the_filters_as_sent(): void
    {
        $this->fakeReport($this->emptyReport(ReportType::MovementHistory, rows: 4));

        $this->actingAsAdmin($this->sara)
            ->get("/api/reports/movement_history/export?format=csv&from=2026-10-20&to=2026-11-19&itemId={$this->gloves->id}")
            ->assertOk();

        $log = ReportExport::sole();
        $this->assertSame([$this->sara->id, 'movement_history', 'csv', 4], [$log->user_id, $log->report_type->value, $log->format->value, $log->row_count]);
        $this->assertSame(['from' => '2026-10-20', 'to' => '2026-11-19', 'itemId' => $this->gloves->id], $log->filters);
        $this->assertSame(['2026-10-20', '2026-11-19'], [$log->period_from->toDateString(), $log->period_to->toDateString()]);
        $this->assertTrue($log->exported_at->equalTo(now()));
    }

    public function test_a_report_that_ignores_the_period_logs_no_period(): void
    {
        $this->fakeReport($this->emptyReport(ReportType::Summary));

        $lines = $this->csv($this->actingAsAdmin($this->sara)->get('/api/reports/summary/export?format=csv&from=2026-10-20&to=2026-11-19')->assertOk());

        $this->assertSame(['Period', 'As of today'], $lines[3]);
        $this->assertNull(ReportExport::sole()->period_from);
        $this->assertNull(ReportExport::sole()->period_to);
    }

    public function test_a_failed_export_records_nothing(): void
    {
        $this->mock(ReportService::class)->shouldReceive('build')->andThrow(new RuntimeException('The database went away.'));

        $this->actingAsAdmin($this->sara)->getJson('/api/reports/summary/export?format=csv')->assertServerError();

        $this->assertSame(0, ReportExport::count());
    }

    // ---- Errors ----------------------------------------------------------------------------

    public function test_the_request_is_checked_before_anything_is_built(): void
    {
        $this->mock(ReportService::class)->shouldNotReceive('build');
        $export = fn (string $query) => $this->actingAsAdmin($this->sara)->getJson("/api/reports/summary/export?{$query}");

        $export('')->assertUnprocessable()->assertJsonPath('errors.format', 'Choose a file format: pdf, xlsx or csv.');
        $export('format=docx')->assertUnprocessable()->assertJsonPath('errors.format', 'Choose a file format: pdf, xlsx or csv.');
        $export('format=csv&from=2026-11-19&to=2026-11-01')->assertUnprocessable()
            ->assertJsonPath('errors.to', 'The end date cannot be before the start date.');
        $export('format=csv&from=19-11-2026')->assertUnprocessable()->assertJsonPath('errors.from', 'The start date is not a valid date.');
        $export('format=csv&categoryId=999')->assertUnprocessable()->assertJsonPath('errors.categoryId', 'Choose a category from the list.');
        $export('format=csv&itemId=999')->assertUnprocessable()->assertJsonPath('errors.itemId', 'Choose an item from the list.');

        $this->actingAsAdmin($this->sara)->getJson('/api/reports/stock_levels/export?format=csv')->assertNotFound();
        $this->assertSame(0, ReportExport::count());
    }

    public function test_a_signed_in_user_is_required(): void
    {
        $this->getJson('/api/reports/summary/export?format=csv')->assertUnauthorized();
    }

    // ---- helpers ---------------------------------------------------------------------------

    private function fakeReport(ReportResult $report): void
    {
        $this->mock(ReportService::class)->shouldReceive('build')->andReturn($report);
    }

    /** A report of $type with $rows identical rows that only the row count reads. */
    private function emptyReport(ReportType $type, int $rows = 0): ReportResult
    {
        $row = match ($type) {
            ReportType::MovementHistory => ['id' => 1, 'itemId' => $this->gloves->id, 'type' => 'incoming', 'reason' => null, 'quantity' => 1,
                'date' => '2026-11-01', 'supplier' => null, 'recipient' => null, 'unitCost' => 1, 'totalValue' => 1],
            default => ['id' => 1, 'itemId' => $this->gloves->id, 'categoryId' => $this->consumables->id, 'quantity' => 1,
                'expiredQuantity' => 0, 'unit' => 'box', 'unitCost' => 1, 'totalValue' => 1, 'status' => 'available'],
        };

        return new ReportResult($type, [], [], array_fill(0, $rows, $row));
    }

    /** The CSV as lines of cells, without the UTF-8 mark; a blank line is []. */
    private function csv(TestResponse $response): array
    {
        $content = substr($response->getContent(), 3);

        return array_map(
            fn (string $line) => $line === '' ? [] : str_getcsv($line, escape: ''),
            explode("\n", rtrim($content, "\n")),
        );
    }
}
