/**
 * GET /reports/{type}/export: BACKEND_HANDOFF.md 4.8, "Export".
 *
 * ReportService::build() is Developer A's (phase 5) and is replaced here by a fake report with the
 * agreed ReportResult shape, so these tests check the export only: the file, the log, the errors.
 */
class ExportReportTest extends TestCase
{
    use RefreshDatabase;

    private User $sara;

    private Category $consumables;

    private Item $gloves;

    protected function setUp(): void
    {
        parent::setUp();
        $this->travelTo('2026-11-19 10:30');
        $this->sara = User::factory()->admin()->create(['name' => 'Sara Ahmed']);
        $this->consumables = Category::factory()->create(['name' => 'Consumables']);
        $this->gloves = Item::factory()->create(['name' => 'Surgical Gloves', 'category_id' => $this->consumables->id, 'unit' => 'box']);
    }

    // ---- The CSV file ----------------------------------------------------------------------

    public function test_a_summary_csv_has_the_report_information_the_table_and_the_totals(): void
    {
        $this->fakeReport(new ReportResult(ReportType::Summary,
            ['totalItems' => 1, 'available' => 0, 'lowStock' => 1, 'outOfStock' => 0], [],
            [['id' => 1, 'itemId' => $this->gloves->id, 'categoryId' => $this->consumables->id, 'quantity' => 8,
                'expiredQuantity' => 2, 'unit' => 'box', 'totalValue' => 96.456, 'status' => 'low_stock']]));

        $response = $this->actingAsAdmin($this->sara)->get('/api/reports/summary/export?format=csv')
            ->assertOk()
            ->assertHeader('Content-Type', 'text/csv; charset=UTF-8')
            ->assertHeader('Content-Disposition', 'attachment; filename="meditrack-summary-2026-11-19.csv"');

        $this->assertStringStartsWith("\xEF\xBB\xBF", $response->getContent(), 'UTF-8 mark for Excel');
        $this->assertSame([
            ['Report', 'Inventory Summary'],
            ['Generated by', 'Sara Ahmed (Admin)'],
            ['Generated at', '2026-11-19 10:30 (Asia/Gaza)'],
            ['Period', 'As of today'],
            ['Category', 'All categories'],
            ['Item', 'All items'],
            ['Rows', '1'],
            [],
            ['Item', 'Category', 'Available Quantity', 'Expired Quantity', 'Unit', 'Status', 'Total Value'],
            ['Surgical Gloves', 'Consumables', '8', '2', 'box', 'Low Stock', '96.46'],
            [],
            ['Totals'],
            ['Total Items', '1'], ['Available', '0'], ['Low Stock', '1'], ['Out of Stock', '0'],
        ], $this->csv($response));
    }

    public function test_movement_history_names_every_filter_and_each_type(): void
    {
        $this->fakeReport(new ReportResult(ReportType::MovementHistory,
            ['incomingCount' => 1, 'outgoingCount' => 1, 'disposalCount' => 1, 'itemsCount' => 1, 'transactionsCount' => 3], [],
            [
                ['id' => 3, 'itemId' => $this->gloves->id, 'type' => 'outgoing', 'reason' => 'expired_disposal', 'quantity' => 2,
                    'date' => '2026-11-15', 'supplier' => null, 'recipient' => null, 'unitCost' => 12, 'totalValue' => 24],
                ['id' => 2, 'itemId' => $this->gloves->id, 'type' => 'outgoing', 'reason' => 'issue', 'quantity' => 5,
                    'date' => '2026-11-10', 'supplier' => null, 'recipient' => 'Ward A', 'unitCost' => 12, 'totalValue' => 60],
                ['id' => 1, 'itemId' => $this->gloves->id, 'type' => 'incoming', 'reason' => null, 'quantity' => 15,
                    'date' => '2026-11-01', 'supplier' => 'MedSupply', 'recipient' => null, 'unitCost' => 12, 'totalValue' => null],
            ]));
        $query = "format=csv&from=2026-10-20&to=2026-11-19&categoryId={$this->consumables->id}&itemId={$this->gloves->id}&search=+glo+";

        $lines = $this->csv($this->actingAsStorekeeper()->get("/api/reports/movement_history/export?{$query}")->assertOk());

        $this->assertSame(['Period', '2026-10-20 to 2026-11-19'], $lines[3]);
        $this->assertSame([['Category', 'Consumables'], ['Item', 'Surgical Gloves'], ['Search', 'glo'], ['Rows', '3']], array_slice($lines, 4, 4));
        $this->assertSame(['Date', 'Item', 'Type', 'Quantity', 'Unit', 'Supplier', 'Recipient', 'Unit Cost', 'Total Value'], $lines[9]);
        $this->assertSame([
            ['2026-11-15', 'Surgical Gloves', 'Expired Disposal', '2', 'box', '', '', '12', '24'],
            ['2026-11-10', 'Surgical Gloves', 'Outgoing', '5', 'box', '', 'Ward A', '12', '60'],
            // A missing value stays empty instead of a made-up 0.
            ['2026-11-01', 'Surgical Gloves', 'Incoming', '15', 'box', 'MedSupply', '', '12', ''],
        ], array_slice($lines, 10, 3));
    }

    public function test_the_report_is_built_with_the_filters_and_every_row(): void
