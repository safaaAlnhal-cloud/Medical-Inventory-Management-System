    // ---- Excel and PDF ---------------------------------------------------------------------

    public function test_an_excel_file_has_the_same_content_with_numbers_kept_as_numbers(): void
    {
        $this->gloves->update(['name' => '=HYPERLINK("http://bad.example")']);
        $this->fakeReport($this->summaryReport());

        $response = $this->actingAsAdmin($this->sara)->get('/api/reports/summary/export?format=xlsx')
            ->assertOk()
            ->assertHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')
            ->assertHeader('Content-Disposition', 'attachment; filename="meditrack-summary-2026-11-19.xlsx"');

        $rows = $this->xlsx($response->getContent());
        $values = array_map(fn (array $cells) => array_map(fn (Cell $cell) => $cell->getValue(), $cells), $rows);

        $this->assertSame(['MediTrack - Inventory Summary'], $values[0]);
        $this->assertSame(['Generated by', 'Sara Ahmed (Admin)'], $values[2]);
        $this->assertContains(['Item', 'Category', 'Available Quantity', 'Expired Quantity', 'Unit', 'Status', 'Total Value'], $values);
        $this->assertContains(['=HYPERLINK("http://bad.example")', 'Consumables', 8, 2, 'box', 'Low Stock', 96.46], $values);
        $this->assertContains(['Low Stock', 1], $values);

        // The name is written as text (inlineStr), and the sheet holds no formula (<f>) for Excel to
        // run. Read from the XML itself: OpenSpout's reader turns any text starting with = back
        // into a formula cell, so it cannot tell.
        $sheet = $this->xlsxSheetXml($response->getContent());
        $this->assertStringContainsString('t="inlineStr"><is><t>=HYPERLINK(&quot;http://bad.example&quot;)</t>', $sheet);
        $this->assertStringNotContainsString('<f>', $sheet);
        $this->assertSame('xlsx', ReportExport::sole()->format->value);
    }

    public function test_a_pdf_file_is_a_pdf_and_is_logged(): void
    {
        $this->fakeReport($this->summaryReport());

        $response = $this->actingAsStorekeeper()->get('/api/reports/summary/export?format=pdf')
            ->assertOk()
            ->assertHeader('Content-Type', 'application/pdf')
            ->assertHeader('Content-Disposition', 'attachment; filename="meditrack-summary-2026-11-19.pdf"');

        $this->assertStringStartsWith('%PDF-', $response->getContent());
        $this->assertSame('pdf', ReportExport::sole()->format->value);
    }

    public function test_the_pdf_page_escapes_names_and_formats_money(): void
    {
        $document = new ReportDocument('MediTrack - Inventory Value', ['Report' => 'Inventory Value'],
            ['Item', 'Quantity', 'Unit Cost', 'Total Value'],
            [['<b>Gauze</b>', 1200, 12.5, null]],
            ['Total Value' => 15000.0, 'Items' => 1], money: [2, 3], moneyTotals: ['Total Value']);

        $html = (new PdfWriter)->html($document);

        $this->assertStringContainsString('&lt;b&gt;Gauze&lt;/b&gt;', $html);
        $this->assertStringNotContainsString('<b>Gauze', $html);
        $this->assertStringContainsString('>1,200<', $html);
        $this->assertStringContainsString('>$12.50<', $html);
        $this->assertStringContainsString('>$15,000.00<', $html);

        $empty = new ReportDocument('MediTrack - Critical Items', [], ['Item', 'Status'], [], []);
        $this->assertStringContainsString('No rows match these filters.', (new PdfWriter)->html($empty));
    }

    // ---- The export log --------------------------------------------------------------------

    public function test_a_successful_export_is_logged_with_the_filters_as_sent(): void
    {
        $this->fakeReport($this->emptyReport(ReportType::MovementHistory, rows: 4));

        $this->actingAsAdmin($this->sara)
            ->get("/api/reports/movement_history/export?format=csv&from=2026-10-20&to=2026-11-19&itemId={$this->gloves->id}")
