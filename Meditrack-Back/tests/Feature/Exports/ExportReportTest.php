    // ---- Errors ----------------------------------------------------------------------------

    public function test_the_request_is_checked_before_anything_is_built(): void
    {
        $this->mock(ReportService::class)->shouldNotReceive('build');
        $export = fn (string $query) => $this->actingAsAdmin($this->sara)->getJson("/api/reports/summary/export?{$query}");

        $export('')->assertUnprocessable()->assertJsonPath('errors.format', 'Choose a file format: pdf, xlsx or csv.');
        $export('format=docx')->assertUnprocessable()->assertJsonPath('errors.format', 'Choose a file format: pdf, xlsx or csv.');
        $export('format=csv&from=2026-11-19&to=2026-11-01')->assertUnprocessable()
            ->assertJsonPath('errors.to', 'The end date cannot be before the start date.');
        $export('format=csv&from=19-11-2026')->assertUnprocessable()->assertJsonPath('errors.from', 'The start date is not a valid date.');
        $export('format=csv&categoryId=999')->assertUnprocessable()->assertJsonPath('errors.categoryId', 'Choose a category from the list.');
        $export('format=csv&itemId=999')->assertUnprocessable()->assertJsonPath('errors.itemId', 'Choose an item from the list.');

        $this->actingAsAdmin($this->sara)->getJson('/api/reports/stock_levels/export?format=csv')->assertNotFound();
        $this->assertSame(0, ReportExport::count());
    }

